/* 접근 코드를 문자열로 남기지 않기 위한 단방향 변환.
   djb2-xor. 암호학적 해시가 아니고 그럴 필요도 없다 — 위의 설명 참고. */
window.BCHash = function (s) {
  var x = 5381;
  for (var i = 0; i < String(s).length; i++) {
    x = (((x << 5) + x) ^ String(s).charCodeAt(i)) >>> 0;
  }
  return x.toString(36);
};

