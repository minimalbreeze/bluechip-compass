/* ============================================================================
   ask-brain.js — 물어보기의 "두뇌": 지시문과 맥락을 만드는 곳
   ----------------------------------------------------------------------------
   답을 만드는 데 필요한 세 가지를 **한 곳에** 둔다.

     · SYSTEM        — AI 에게 주는 지시문(무엇을 지키고 무엇을 하지 않는가)
     · buildContext  — 이 앱이 이미 아는 것(국면·오늘 기사·종목 해설)을 붙인다
     · SHAPE         — 앱이 화면에 쓸 값(자리·비율 등)의 모양

   화면(ask.js)에 섞어 두지 않는 이유: 화면은 자주 고치고 지시문은 거의 안
   고친다. 섞어 두면 화면을 손보다가 지시문을 건드리게 된다.

   ⚠️ **금액은 이 파일이 애초에 받지 않는다.** buildContext 의 입력에 시드가
      없다. 답은 "전체 투자금의 몇 %" 로 오고, 원 단위 환산은 ask.js 가
      브라우저 안에서 한다. 여기에 금액 인자를 더하지 말 것 — 그 순간
      "금액은 어디에도 보내지 않는다"는 약속이 깨진다.

   ⚠️ 여기에는 DOM 도 fs 도 쓰지 않는다. 브라우저에서는 `window.BCAskBrain`
      으로 잡히고, Node 에서도 그대로 불러올 수 있어서 지시문과 맥락을
      브라우저 없이 확인할 수 있다(`node -e "require('./ask-brain.js')..."`).
   ========================================================================== */
(function (root, make) {
  var api = make();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.BCAskBrain = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  var SYSTEM = `당신은 한국 개인투자자용 앱 "블루칩 나침반"의 상담 담당입니다.

## 읽는 사람
주식을 처음 시작하는 평범한 사람입니다. **노후자금**을 굴리려는 사람이고,
단타(데이트레이딩)를 하려는 사람이 아닙니다. 크게 버는 것보다 **크게 다치지
않는 것**이 훨씬 중요합니다.

## 반드시 지킬 것

1. **매수·매도를 권하지 마세요.** "사세요", "파세요", "지금이 기회",
   "저평가/고평가", 목표주가, 매수 타이밍은 쓰지 마세요.
   대신 **자리**로 답하세요 — 노후자금의 중심(코어) 자리인가, 곁다리(위성)
   자리인가, 지금은 지켜보는 자리인가, 이 목적과 아예 맞지 않는가.
   "이 목적에는 맞지 않아 보인다"는 말은 해도 됩니다. 그건 가격 예측이 아니라
   **목적과의 적합성** 판단입니다.

2. **금액으로 답하지 마세요. 비율로만 답하세요.** 이 사람의 투자금이 얼마인지
   당신은 모르고, 알아서도 안 됩니다. "전체 투자금의 몇 %"로만 말하세요.
   원 단위 환산은 앱이 사용자 기기 안에서 합니다.

3. **단타 질문에는 그 목적이 이 앱과 다르다고 말하세요.** 며칠 안의 등락,
   "언제 사면 되나", "얼마까지 갈까"는 답하지 말고 그 이유를 짧게 적으세요.

4. **모르면 모른다고 하세요.** 최근 실적이나 사건을 확실히 모르면 지어내지
   말고 "여기까지는 확인이 안 됩니다. 아래 원자료에서 직접 보세요"라고 쓰세요.

5. **수치를 단정하지 마세요.** PER, 부채비율, 목표주가 같은 숫자를 사실처럼
   적지 마세요. 대신 "무엇을 확인해야 하는지" 이름으로 알려주세요.

6. 존댓말로, 짧은 문장으로, 어려운 말에는 괄호로 뜻을 달아 쓰세요.
   전체를 휴대폰 한두 화면 안에서 읽을 수 있는 길이로 쓰세요.

7. 마지막에 "손실이 날 수도 있고 판단은 본인의 몫"이라는 취지를 한 줄로
   적으세요. 어떤 수익도 보장하지 마세요.`;

  var EXTRACT_SYSTEM =
    '아래 상담 답변에서 값만 뽑아 정리하세요. ' +
    '새로운 판단을 만들지 말고 글에 있는 것만 옮기세요.';

  /* 앱이 쓸 값의 모양. 두 길이 같은 값을 뽑아야 해서 여기 적어 둔다. */
  var SHAPE = {
    verdict: 'core=노후자금의 중심 자리로 볼 만함 / satellite=곁다리 자리까지 / watch=지금은 지켜보는 자리 / unsuited=이 목적과 맞지 않음 / general=종목 판단이 아닌 일반 질문',
    headline: '답을 한 문장으로. 20자 안팎',
    pctLo: '전체 투자금 대비 하한 %. 해당 없으면 0',
    pctHi: '전체 투자금 대비 상한 %. 담지 않는 쪽이거나 일반 질문이면 0',
    checks: '사용자가 직접 확인할 것의 이름. 없으면 빈 배열'
  };

  /* ── 맥락 만들기 ────────────────────────────────────────────
     o = {
       style, mk, question,
       regime: live.regime[mk] | null,
       news:   [{ko|title}, ...],
       asOf,
       stock:  {name, ticker} | null,
       card:   analysis.json 의 그 종목 항목 | null,
       chg:    오늘 등락 % | null
     }
     ⚠️ **금액은 넣지 않는다.** 답은 "전체 투자금의 몇 %" 로만 받고,
        원 단위 환산은 사용자 기기에서만 한다. */
  function buildContext(o) {
    var p = [];
    p.push('## 이 사람에 대해 아는 것');
    p.push('- 투자 성향: ' + (o.style || '알 수 없음'));
    p.push('- 보고 있는 시장: ' + (o.mk === 'us' ? '미국(나스닥·S&P 500)' : '한국(코스피)'));
    p.push('- 목적: 노후자금을 손실 없이 불려 나가는 것. 단타가 아님');
    p.push('- 투자 금액은 알려주지 않습니다. 비율로만 답하세요.');

    var rg = o.regime;
    if (rg) {
      p.push('\n## 지금 시장 국면 (이 앱이 실제 수치로 판정한 것)');
      if (rg.summary) p.push('- ' + rg.summary);
      p.push('- 금리 ' + rg.rates + ' / 경기 ' + rg.growth + ' / 밸류 ' + rg.valuation +
        ' / 환율 ' + rg.fx + ' / 지정학 ' + rg.geo);
    }

    if (o.stock && o.stock.ticker) {
      /* 사용자가 이 종목 화면에서 물었다는 뜻이지, 반드시 이 종목을 묻는다는
         뜻은 아니다. 삼성전자를 보다가 다른 회사를 물을 수도 있다. */
      p.push('\n## 질문할 때 보고 있던 종목 (참고용. 질문의 주제가 아닐 수도 있습니다)\n- ' +
        o.stock.name + ' (' + o.stock.ticker + ')');
      if (o.card) {
        p.push('\n### 이 앱이 이미 정리해 둔 내용 (여기서 벗어나는 말을 할 때는 왜인지 적으세요)');
        if (o.card.one) p.push('- 뭐하는 회사: ' + o.card.one);
        if (o.card.risk) p.push('- 이 판단을 깨뜨리는 것: ' + o.card.risk);
        if (o.card.scores) p.push('- 6축 점수(각 5점): ' + JSON.stringify(o.card.scores));
      } else {
        p.push('- 이 앱에는 아직 이 종목 해설이 없습니다. 없다는 사실을 답에 적어 주세요.');
      }
      if (typeof o.chg === 'number') p.push('- 오늘 등락: ' + o.chg + '%');
    }

    var news = o.news || [];
    if (news.length) {
      p.push('\n## 오늘 이 시장 기사 제목 (' + (o.asOf || '') + ')');
      news.slice(0, 12).forEach(function (n) { p.push('- ' + (n.ko || n.title || '')); });
    }

    p.push('\n## 물어본 것\n' + o.question);
    p.push('\n위 질문에 답하세요. 아래 순서로, 각 항목은 짧게:\n' +
      '**뭘 물어보셨는지** / **뭐하는 회사인지**(종목 질문일 때) / ' +
      '**요즘 상황**(확인 안 되면 안 된다고) / **10년 뒤에도 있을 회사인지** / ' +
      '**노후자금에서 어떤 자리인지** / **담는다면 전체 투자금의 몇 %까지인지와 그 이유** / ' +
      '**직접 확인할 것** / **한 줄 고지**');
    return p.join('\n');
  }

  return {
    SYSTEM: SYSTEM,
    EXTRACT_SYSTEM: EXTRACT_SYSTEM,
    SHAPE: SHAPE,
    MODEL: 'claude-opus-5',
    buildContext: buildContext
  };
});
